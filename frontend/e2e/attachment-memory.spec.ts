import { test, expect } from "@playwright/test";

// 从实际上传到人物澄清、逐项批准及正式来源，验证朋友资料不会默认保存为本人事实。
test("附件候选明确人物后逐项保存并保留文件出处", async ({ page }) => {
  const base = `http://127.0.0.1:${process.env.TEST_MODEL_PORT || "18113"}/v1`;
  await page.request.put("/api/settings", { data: { base_url: base, model: "chat", api_key: "test-only" } });
  await page.request.put("/api/settings/embedding", { data: { base_url: base, model: "embed", dimensions: 3, api_key: "test-only" } });
  expect((await (await page.request.post("/api/settings/capabilities/embedding")).json()).status).toBe("passed");
  await page.goto("/");
  await page.getByRole("button", { name: "新建会话" }).click();
  await expect(page.getByLabel("上传会话附件")).toBeEnabled();
  await page.getByLabel("上传会话附件").setInputFiles({ name: "朋友.txt", mimeType: "text/plain", buffer: Buffer.from("陈敏住在杭州。陈敏喜欢乌龙茶。") });
  await expect(page.getByText("可用 · 朋友.txt", { exact: true })).toBeVisible();
  await page.getByLabel("消息", { exact: true }).fill("请从附件提取长期记忆");
  await page.getByRole("button", { name: "发送消息" }).click();
  const card = page.getByTestId("memory-candidate").filter({ hasText: "住在杭州" });
  await expect(card).toContainText("人物尚未核对");
  await expect(card.getByRole("button", { name: "确认保存" })).toBeDisabled();
  await expect(card.getByRole("link", { name: "朋友.txt" })).toBeVisible();
  await expect(card).toContainText("来源原文：陈敏住在杭州");
  await page.reload();
  await expect(card).toContainText("人物尚未核对");
  await card.getByLabel("事实归属").selectOption("other");
  await card.getByLabel("人物名称或关系").fill("陈敏（朋友）");
  await card.getByRole("button", { name: "更新人物预览" }).click();
  await expect(card).toContainText("人物：陈敏（朋友）。事实：住在杭州");
  expect((await (await page.request.get("/api/memories")).json()).length).toBe(0);
  await card.getByRole("button", { name: "确认保存" }).click();
  await expect(card).toContainText("已确认并保存");
  const other = page.getByTestId("memory-candidate").filter({ hasText: "喜欢乌龙茶" });
  await other.getByRole("button", { name: "拒绝" }).click();
  await expect(other).toContainText("已拒绝，未保存");
  await page.reload();
  await expect(card).toContainText("已确认并保存");
  await expect(other).toContainText("已拒绝，未保存");
  await page.getByRole("button", { name: "长期记忆", exact: true }).click();
  const entry = page.getByTestId("memory-entry");
  await expect(entry).toHaveCount(1);
  await expect(entry).toContainText("人物：陈敏（朋友）。事实：住在杭州");
  await expect(entry.getByRole("link", { name: "朋友.txt" })).toBeVisible();
  await entry.screenshot({ path: "test-results/attachment-memory-source.png" });
});
