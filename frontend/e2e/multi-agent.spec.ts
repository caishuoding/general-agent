import { test, expect } from "@playwright/test";
import { configureSearchModel } from "./auth";

// 通过真实主从工具流验证只读子会话、多轮任务及刷新恢复。
test("主智能体汇总子任务并可查看只读会话", async ({ page }) => {
  const modelUrl = `http://127.0.0.1:${process.env.TEST_MODEL_PORT || "18081"}/v1`;
  await configureSearchModel(page, modelUrl, modelUrl);
  await page.goto("/");
  await page.getByRole("button", { name: /新建会话|开始新对话/ }).click();
  await page.getByRole("textbox", { name: "消息", exact: true }).fill("__multi_agent_browser__");
  await page.getByRole("button", { name: "发送消息" }).click();
  // 子智能体通过后台调度完成后再由主智能体汇总，给异步执行留出稳定的完成窗口。
  await expect(page.getByText("主智能体已经汇总子任务。", { exact: true })).toBeVisible({ timeout: 20_000 });
  const task = page.getByRole("button", { name: "研究子任务 · 已完成" });
  await expect(task).toBeVisible();
  await expect(page.getByRole("list", { name: "子智能体" })).toHaveCSS("display", "flex");
  await expect(task.locator(".agent-task-avatar-initials")).toHaveText("研究");
  await expect(page.getByText("子智能体补充交付结果。", { exact: true })).toHaveCount(0);
  const taskBox = await task.boundingBox();
  const answerBox = await page.getByText("主智能体已经汇总子任务。", { exact: true }).boundingBox();
  expect(taskBox).not.toBeNull();
  expect(answerBox).not.toBeNull();
  expect(taskBox!.y).toBeLessThan(answerBox!.y);
  await expect(page.getByText("子智能体公开交付结果。", { exact: true })).toHaveCount(0);
  await task.click();
  const dialog = page.getByRole("dialog", { name: "研究子任务" });
  await expect(dialog).toBeVisible();
  await expect(dialog.getByText("第 1 轮", { exact: true })).toBeVisible();
  await expect(dialog.getByRole("heading", { name: "子智能体结论" })).toBeVisible();
  await expect(dialog.getByRole("listitem").filter({ hasText: "已完成官方来源核验" })).toBeVisible();
  await expect(dialog.getByText("## 子智能体结论", { exact: true })).toHaveCount(0);
  await expect(dialog.getByText("第 2 轮", { exact: true })).toBeVisible();
  await expect(dialog.getByText("子智能体补充交付结果。", { exact: true })).toBeVisible();
  const firstReply = dialog.locator(".agent-chat-subagent").filter({ hasText: "子智能体公开交付结果。" });
  await expect(firstReply.getByText("参考来源 · 2", { exact: true })).toBeVisible();
  await expect(firstReply.getByRole("link", { name: "API 定价 - 智谱AI开放文档", exact: true })).toHaveCount(0);
  await firstReply.locator(".answer-citation").first().click();
  await expect(firstReply.getByRole("link", { name: "API 定价 - 智谱AI开放文档", exact: true })).toHaveCount(1);
  await expect(firstReply.getByRole("link", { name: "模型 API 价格", exact: true })).toHaveCount(1);
  await expect(firstReply.locator(".agent-message-sources li").first()).toBeFocused();
  await expect(firstReply.locator(".agent-message-markdown strong")).toHaveCSS("display", "inline");
  await firstReply.getByRole("button", { name: "参考来源 · 2", exact: true }).click();
  await expect(firstReply.locator(".agent-message-sources li")).toHaveCount(0);
  await expect(firstReply.getByText(/^W\d+$/, { exact: true })).toHaveCount(0);
  await expect(dialog.getByText("此会话由主智能体管理，无法直接输入。", { exact: true })).toBeVisible();
  await expect(dialog.getByRole("textbox")).toHaveCount(0);
  await dialog.getByRole("button", { name: "关闭子任务会话" }).click();
  await page.reload();
  await expect(task).toBeVisible();
  await task.click();
  await expect(dialog.getByText("子智能体补充交付结果。", { exact: true })).toBeVisible();
});
